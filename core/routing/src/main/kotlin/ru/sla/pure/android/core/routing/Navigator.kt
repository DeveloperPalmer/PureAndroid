package ru.sla.pure.android.core.routing

import androidx.navigation3.runtime.NavKey

/** Управляет стеками экранов и флоу. Все операции выполняются в главном потоке. */
interface Navigator {
  /** Заменяет весь стек приложения одной записью [route]. */
  fun setRoot(route: NavKey)

  /**
   * Добавляет [route] наверх активного стека.
   * Если маршрут уже в стеке, возвращается к этой записи. Ключ вкладки переключает вкладку и сохраняет её историю.
   */
  fun push(route: NavKey)

  /**
   * Заменяет верхнюю запись активного стека на [route]. В пустом стеке добавляет маршрут.
   * Если запись уже есть в активном стеке, возвращается к ней. Ключ другой вкладки открывает её стек.
   */
  fun replaceTop(route: NavKey)

  /**
   * Удаляет верхнюю запись активного стека. С корня другой вкладки возвращает на стартовую вкладку.
   * На корне стартовой вкладки оставляет стек как есть.
   */
  fun pop()

  /** Удаляет записи над ближайшим [route] в активном стеке. Если маршрут отсутствует, стек сохраняется. */
  fun popTo(route: NavKey)

  /** Очищает стек AppFlow, закрывая открытые в нём флоу. */
  fun removeAll()

  /** Закрывает флоу с идентификатором [flowScope], соответствующим [FlowNavKey.id], вместе с его экранами. */
  fun removeAll(flowScope: String)
}
