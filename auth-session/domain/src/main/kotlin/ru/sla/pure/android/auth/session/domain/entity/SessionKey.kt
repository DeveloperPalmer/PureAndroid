package ru.sla.pure.android.auth.session.domain.entity

/**
 * Ключ, неизменный в пределах одной сессии пользователя: от входа до выхода.
 * Обновление токенов не меняет ключ.
 *
 * Генерируется после входа и сохраняется, пока пользователь авторизован,
 * в том числе после завершения процесса приложения и обновления токенов.
 * Заменяется или сбрасывается только при новом входе либо выходе текущего пользователя.
 *
 * Может использоваться вместо userId, пока идентификатор пользователя недоступен.
 *
 * Например, ключ позволяет отделить кэш авторизованного пользователя,
 * когда профиль с его идентификатором ещё не получен.
 */
@JvmInline
value class SessionKey(val value: String) {
  override fun toString(): String {
    return value
  }
}
